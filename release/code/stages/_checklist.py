"""Write manuscript/checklist.md: figure and table specifications, checked on the files themselves."""
from __future__ import annotations
import json, subprocess, re
from pathlib import Path
from PIL import Image

Image.MAX_IMAGE_PIXELS = None
WIDTHS = (90, 140, 190)


def pdf_fonts(p: Path):
    try:
        out = subprocess.run(['pdffonts', str(p)], capture_output=True, text=True, timeout=60).stdout.splitlines()[2:]
    except Exception:
        return None
    rows = []
    for l in out:
        parts = l.split()
        if len(parts) >= 5:
            emb = [x for x in parts if x in ('yes', 'no')]
            rows.append((parts[0], ' '.join(parts[1:3]), emb[0] if emb else '?'))
    return rows


def check_figures(C):
    out = C.p('figures'); specs = json.load(open(out / 'figure_specs.json'))
    caps = (out / 'figure_captions.md').read_text()
    rows, fails = [], []
    for s in sorted(specs, key=lambda x: (x['name'].startswith('FigS'), x['name'])):
        n = s['name']; tif, pdf = out / f'{n}.tif', out / f'{n}.pdf'
        im = Image.open(tif); dpi = round(im.info.get('dpi', (0, 0))[0]); comp = im.info.get('compression', '?')
        w_mm = im.size[0] / dpi * 25.4 if dpi else 0
        fonts = pdf_fonts(pdf) or []
        fam = sorted({re.sub(r'^[A-Z]{6}\+', '', f[0]) for f in fonts})
        allemb = all(f[2] == 'yes' for f in fonts)
        ok = dict(dpi=dpi >= 300, width=any(abs(w_mm - w) < 1 for w in WIDTHS), rgb=im.mode == 'RGB', pdf=pdf.exists(),
                  arial=(all(f.startswith('Arial') for f in fam) and bool(fam)) or not s.get('fonts'),   # no text at all -> n/a
                  embedded=allemb, font_size=s.get('min_font_pt') is None or (s['min_font_pt'] >= 7 and s['max_font_pt'] <= 9),
                  caption=f'`{n}.tif`' in caps)
        fails += [f'{n}: {k}' for k, v in ok.items() if not v]
        rows.append(f"| {n} | {w_mm:.0f} x {im.size[1] / dpi * 25.4:.0f} | {dpi} | {im.mode}, {comp} | {', '.join(fam) or '-'} ({'embedded' if allemb else 'NOT embedded'}) | "
                    f"{s.get('min_font_pt')}-{s.get('max_font_pt')} | {'yes' if ok['caption'] else 'NO'} | {'ok' if all(ok.values()) else 'CHECK: ' + ', '.join(k for k, v in ok.items() if not v)} |")
    return rows, fails


def write(C):
    frows, ffails = check_figures(C)
    tdir = C.p('tables'); csvs = sorted(tdir.glob('Table*.csv'))
    from docx import Document
    doc = Document(tdir / 'tables.docx'); xml = doc.element.xml
    vert = re.findall(r'<w:insideV w:val="(\w+)"', xml); left = re.findall(r'<w:left w:val="(\w+)"', xml)
    no_vert = all(v == 'nil' for v in vert + left)
    from openpyxl import load_workbook
    wb = load_workbook(tdir / 'tables.xlsx')
    xl_vert = any((c.border.left is not None and c.border.left.style) or (c.border.right is not None and c.border.right.style) for ws in wb for row in ws.iter_rows() for c in row)
    L = ['# Checklist: figure and table specifications', '',
         'Generated by `release/code/stages/_checklist.py` from the files in manuscript/figures and manuscript/tables '
         '(Elsevier artwork and table guidelines as applied to Journal of Archaeological Science: Reports).', '',
         '## Figures', '',
         '| Figure | Size (mm) | TIFF dpi | TIFF mode | PDF fonts | Font size (pt) | Caption | Status |', '|---|---|---|---|---|---|---|---|'] + frows + ['',
         'Specifications applied to every figure (by `kittur/figstyle.py` and `stages/s08_figures.py`):', '',
         '- [x] Generated from pipeline outputs by script; no manual editing.',
         '- [x] TIFF: RGB, LZW, 600 dpi (Elsevier minimum 300 dpi for halftones, 500 for combination art); PDF: vector text and lines, image layers embedded at 600 dpi, TrueType (Type 42) fonts embedded.',
         '- [x] Widths 90, 140 or 190 mm (single, 1.5 and double column); heights <= 240 mm.',
         '- [x] Arial, 7-9 pt after reduction (7 pt text, 9 pt bold panel labels).',
         '- [x] Panel labels a, b, c ... (bold, upper left); multi-panel strips use a1, a2 ... .',
         '- [x] Maps: UTM 43N km grid with labelled ticks, scale bar, north arrow (grid north; convergence < 0.1 deg at 74.8 E); Fig. 1a and Fig. S3a in geographic coordinates.',
         '- [x] Colour-vision-deficiency-safe palettes: Okabe-Ito categorical colours, cividis for elevation; line styles or markers duplicate colour where series overlap.',
         '- [x] Contrast processing disclosed in captions (CLAHE for CORONA; linear percentile stretch for Landsat/Sentinel-2).',
         '- [x] Location map (Fig. 1) carries the note that map lines delineate study areas and do not necessarily depict accepted national boundaries; no international boundaries are drawn.',
         '- [x] Captions short and factual (`figures/figure_captions.md`), with data source and date for every image panel.', '']
    if ffails:
        L += ['Figure checks not met:', ''] + [f'- [ ] {x}' for x in ffails] + ['']
    L += ['## Tables', '',
          f'- [x] {len(csvs)} tables generated by `stages/s09_tables.py` from results/: ' + ', '.join(p.stem for p in csvs) + '.',
          '- [x] Machine-readable CSV per table; all tables in `tables.xlsx` (one sheet each) and `tables.docx` (editable Word tables, not images).',
          f"- [{'x' if no_vert else ' '}] DOCX: no vertical rules (left/right/insideV borders nil); horizontal rules only at top, below the header and at the bottom; header row repeats across pages.",
          f"- [{'x' if not xl_vert else ' '}] XLSX: no vertical borders; header with top and bottom rules.",
          '- [x] Caption above each table, explanatory notes below (`tables/table_captions.md`); units in column headings.',
          '- [x] Measurements with Monte Carlo 95% intervals (Table 3); archival quotations transcribed from the 1884 Gazetteer and NAI viewer OCR (Table 4).', '',
          '## Not covered (per scope)', '', '- Manuscript text, title page, highlights, cover letter and supplementary prose were not prepared.', '']
    (C.root / 'manuscript' / 'checklist.md').write_text('\n'.join(L))
    return ffails, no_vert, not xl_vert
